//! Compiles the Slint UI with the fluent style, embeds the application manifest (per-monitor
//! v2 DPI awareness, Windows 10/11 supportedOS), as the spike does (ADR 0001), and links the app
//! icon and version information (`lastdrop.rc`, compiled with the Windows SDK's `rc.exe`). The
//! version information (`version.rc` in `OUT_DIR`, [`version_rc`]) comes from the package's
//! version and authors and `LICENSE-MIT`'s copyright line, so nothing else needs bumping.

use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let config = slint_build::CompilerConfiguration::new().with_style("fluent".into());
    slint_build::compile_with_config("ui/app.slint", config).expect("Slint UI compiles");

    let dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let manifest = Path::new(&dir).join("app.manifest");
    println!("cargo:rerun-if-changed=app.manifest");
    println!("cargo:rustc-link-arg-bins=/MANIFEST:EMBED");
    println!(
        "cargo:rustc-link-arg-bins=/MANIFESTINPUT:{}",
        manifest.display()
    );

    let dir = Path::new(&dir);
    println!("cargo:rerun-if-changed=lastdrop.rc");
    println!("cargo:rerun-if-changed=icons/lastdrop.ico");
    println!("cargo:rerun-if-env-changed=LASTDROP_RC");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let license = dir.join("../../LICENSE-MIT");
    println!("cargo:rerun-if-changed={}", license.display());
    let license = std::fs::read_to_string(&license).expect("LICENSE-MIT reads");
    std::fs::write(out_dir.join("version.rc"), version_rc(&license)).expect("version.rc writes");
    let out = out_dir.join("lastdrop.res");
    let rc = rc_exe();
    let status = Command::new(&rc)
        .current_dir(dir)
        .args(["/nologo", "/i"])
        .arg(&out_dir)
        .arg("/fo")
        .arg(&out)
        .arg("lastdrop.rc")
        .status()
        .unwrap_or_else(|e| panic!("{} runs: {e}", rc.display()));
    assert!(status.success(), "rc.exe compiles lastdrop.rc: {status}");
    println!("cargo:rustc-link-arg-bins={}", out.display());
}

/// The `VERSIONINFO` resource: file and product version from the package version
/// (`0.2.2` → `0,2,2,0`), the company from its authors, the copyright from `license` (the MIT
/// licence's `Copyright (c) 2026 2Fivers` line) and the licence. ASCII only: `rc.exe` reads the
/// file in the ANSI code page.
fn version_rc(license: &str) -> String {
    let env = |key: &str| std::env::var(key).unwrap_or_else(|_| panic!("{key} is set by Cargo"));
    let part = |key: &str| env(key).parse::<u16>().expect("a version part fits a u16");
    let numbers = format!(
        "{},{},{},0",
        part("CARGO_PKG_VERSION_MAJOR"),
        part("CARGO_PKG_VERSION_MINOR"),
        part("CARGO_PKG_VERSION_PATCH")
    );
    let version = env("CARGO_PKG_VERSION");
    let company = env("CARGO_PKG_AUTHORS");
    let copyright = license
        .lines()
        .map(str::trim)
        .find(|l| l.starts_with("Copyright"))
        .expect("LICENSE-MIT has a copyright line");
    let notice = format!("{copyright}. {}.", env("CARGO_PKG_LICENSE"));
    for text in [&version, &company, &notice] {
        assert!(
            text.is_ascii() && !text.contains('"'),
            "version information is plain ASCII without quotes: {text}"
        );
    }
    format!(
        r#"// Generated by build.rs from Cargo.toml and LICENSE-MIT; do not edit.
1 VERSIONINFO
FILEVERSION {numbers}
PRODUCTVERSION {numbers}
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904B0"
        BEGIN
            VALUE "CompanyName", "{company}"
            VALUE "FileDescription", "Lastdrop"
            VALUE "FileVersion", "{version}"
            VALUE "InternalName", "lastdrop"
            VALUE "LegalCopyright", "{notice}"
            VALUE "OriginalFilename", "lastdrop.exe"
            VALUE "ProductName", "Lastdrop"
            VALUE "ProductVersion", "{version}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#
    )
}

/// The resource compiler: `LASTDROP_RC` if set, else the newest x64 `rc.exe` of the Windows 10/11
/// SDK, which the MSVC toolchain needs anyway (its import libraries).
fn rc_exe() -> PathBuf {
    if let Some(rc) = std::env::var_os("LASTDROP_RC") {
        return PathBuf::from(rc);
    }
    let programs = std::env::var_os("ProgramFiles(x86)")
        .map_or_else(|| PathBuf::from(r"C:\Program Files (x86)"), PathBuf::from);
    let bin = programs.join(r"Windows Kits\10\bin");
    let newest = std::fs::read_dir(&bin)
        .into_iter()
        .flatten()
        .flatten()
        .map(|e| e.path().join(r"x64\rc.exe"))
        .filter(|rc| rc.is_file())
        // Version folders (10.0.26100.0) sort correctly as version numbers, not as text.
        .max_by_key(|rc| sdk_version(rc));
    newest.unwrap_or_else(|| {
        panic!(
            "rc.exe not found under {}; install the Windows SDK or set LASTDROP_RC",
            bin.display()
        )
    })
}

/// The SDK version of `…\bin\<version>\x64\rc.exe` as numbers (`10.0.26100.0` → [10, 0, 26100, 0]).
fn sdk_version(rc: &Path) -> Vec<u32> {
    rc.ancestors()
        .nth(2)
        .and_then(Path::file_name)
        .and_then(|n| n.to_str())
        .map(|n| n.split('.').map(|p| p.parse().unwrap_or(0)).collect())
        .unwrap_or_default()
}
